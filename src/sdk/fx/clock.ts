import gsap from 'gsap'

/**
 * Отбирает у GSAP управление временем и передаёт его игровому тикеру.
 *
 * По умолчанию GSAP регистрирует свой `updateRoot` во внутреннем тикере на
 * requestAnimationFrame и двигает анимации сам. Эта функция снимает его
 * оттуда: после вызова ничего не анимируется, пока время не задаст
 * `advanceAnimations`. Их всегда используют в паре.
 *
 * Зачем:
 *  - порядок внутри кадра гарантирован. Тик GameApp идёт с приоритетом HIGH,
 *    рендер Pixi — с LOW, поэтому раскладка и анимации всегда успевают до
 *    отрисовки. Со своим циклом GSAP порядок зависел бы от очерёдности
 *    регистрации, а на нём держится отсутствие мигания при ресайзе;
 *  - работает ограничение дельты от Pixi: после переключения вкладки
 *    анимации продвинутся на шаг не больше предельного, а не прыгнут;
 *  - анимации встают вместе с остановкой тикера — один выключатель, не два.
 *
 * Если этот вызов убрать, GSAP будет получать время из двух источников
 * одновременно, причём разного: наше начинается с нуля на первом тике, а
 * отсчёт GSAP — с загрузки модуля. Корневое время станет скакать между двумя
 * значениями каждый кадр, и все анимации задрожат.
 */
export function takeOverAnimationClock(): void {
  gsap.ticker.remove(gsap.updateRoot)
}

/**
 * Продвигает все анимации к указанному моменту.
 * `totalSeconds` — время с начала игры, а не шаг кадра.
 */
export function advanceAnimations(totalSeconds: number): void {
  gsap.updateRoot(totalSeconds)
}
