import type { Orientation } from '../app/viewport'

/**
 * Где и какого размера стоит объект. Все числа — доли экрана (0..1),
 * поэтому раскладка не зависит от разрешения устройства.
 */
export type Placement = {
  /** Положение по горизонтали: 0 — левый край, 0.5 — центр, 1 — правый край. */
  x: number
  /** Положение по вертикали: 0 — верх, 0.5 — центр, 1 — низ. */
  y: number
  /** Какая точка самого объекта попадёт в (x, y). По умолчанию его центр. */
  anchorX?: number
  anchorY?: number
  /** Вписать объект в такую долю ширины экрана. Пропорции сохраняются. */
  fitWidth?: number
  /** Вписать объект в такую долю высоты экрана. Пропорции сохраняются. */
  fitHeight?: number
  /** Домножить итоговый масштаб. Удобно для мелкой подгонки. */
  scale?: number
  /**
   * Относительно чего считать доли:
   * 'safe'   — экран без системных отступов (по умолчанию, для всего управления);
   * 'screen' — весь экран целиком (для фона, который должен закрывать всё).
   */
  area?: 'safe' | 'screen'
}

/**
 * Раскладка сцены: для каждого объекта — своё место в портрете и в альбоме.
 * Это обычные данные, поэтому вся вёрстка экрана видна в одном файле конфига.
 */
export type LayoutScheme<Key extends string = string> = Record<Key, Record<Orientation, Placement>>
