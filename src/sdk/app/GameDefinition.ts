import type { GameApp } from './GameApp'

/**
 * Описание игры для точки входа.
 *
 * Это весь контракт, который нужно выполнить новой игре, чтобы её можно было
 * запустить. Всё остальное — ресурсы, арт, источник спинов, сцены, горячие
 * клавиши — игра собирает внутри `start` сама, и точка входа об этом не знает.
 */
export type GameDefinition = {
  /**
   * Цвет фона страницы под сценой.
   *
   * Вынесен отдельно, потому что нужен раньше `start`: Pixi задаёт цвет
   * очистки кадра при инициализации, до появления первой сцены.
   */
  background: number

  /** Грузит ресурсы и показывает свои сцены. */
  start(app: GameApp): Promise<void>
}
